-- originadas por parceiros ativos. Comissão padrão: 30% por 12 meses.

alter table public.users
  add column if not exists woovi_subscription_value_cents integer,
  add column if not exists woovi_subscription_correlation_id text;

create table if not exists public.promotion_campaigns (
  key text primary key,
  name text not null,
  plan_key text not null check (plan_key in ('starter','pro')),
  promo_price_cents integer not null check (promo_price_cents > 0),
  regular_price_cents integer not null check (regular_price_cents > 0),
  max_redemptions integer not null check (max_redemptions > 0),
  reserved_count integer not null default 0 check (reserved_count >= 0),
  redeemed_count integer not null default 0 check (redeemed_count >= 0),
  active boolean not null default true,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.partner_profiles (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.users(id) on delete cascade,
  display_name text not null,
  social_handle text,
  social_url text,
  audience_size integer check (audience_size is null or audience_size >= 0),
  payout_pix_key text,
  status text not null default 'pending' check (status in ('pending','active','paused','rejected')),
  commission_percent numeric(5,2) not null default 30 check (commission_percent >= 0 and commission_percent <= 100),
  commission_months integer not null default 12 check (commission_months between 1 and 60),
  approved_by uuid references public.users(id) on delete set null,
  approved_at timestamptz,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.partner_profiles
  add column if not exists terms_accepted_at timestamptz,
  add column if not exists terms_version text;

create index if not exists partner_profiles_status_idx on public.partner_profiles(status, created_at desc);

create table if not exists public.partner_codes (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partner_profiles(id) on delete cascade,
  campaign_key text references public.promotion_campaigns(key) on delete set null,
  code text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(partner_id, code)
);
create unique index if not exists partner_codes_upper_unique_idx on public.partner_codes(upper(code));
create index if not exists partner_codes_partner_idx on public.partner_codes(partner_id, active);

create table if not exists public.partner_clicks (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partner_profiles(id) on delete cascade,
  code_id bigint not null references public.partner_codes(id) on delete cascade,
  visitor_id text not null,
  referrer text,
  created_at timestamptz not null default now(),
  unique(code_id, visitor_id)
);
create index if not exists partner_clicks_partner_idx on public.partner_clicks(partner_id, created_at desc);

create table if not exists public.partner_referrals (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partner_profiles(id) on delete cascade,
  code_id bigint not null references public.partner_codes(id) on delete restrict,
  user_id uuid not null unique references public.users(id) on delete cascade,
  campaign_key text references public.promotion_campaigns(key) on delete set null,
  status text not null default 'trial' check (status in ('trial','paid','cancelled')),
  promo_reserved boolean not null default false,
  promo_price_cents integer,
  regular_price_cents integer,
  reserved_at timestamptz,
  redeemed_at timestamptz,
  first_paid_at timestamptz,
  last_paid_at timestamptz,
  attributed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists partner_referrals_partner_idx on public.partner_referrals(partner_id, created_at desc);
create index if not exists partner_referrals_code_idx on public.partner_referrals(code_id, created_at desc);

create table if not exists public.partner_commissions (
  id bigint generated by default as identity primary key,
  partner_id bigint not null references public.partner_profiles(id) on delete cascade,
  referral_id bigint not null references public.partner_referrals(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  woovi_event_id text not null unique,
  payment_value_cents integer not null check (payment_value_cents > 0),
  commission_percent numeric(5,2) not null,
  commission_value_cents integer not null check (commission_value_cents >= 0),
  status text not null default 'pending' check (status in ('pending','approved','paid','reversed')),
  eligible_at timestamptz not null default (now() + interval '14 days'),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists partner_commissions_partner_idx on public.partner_commissions(partner_id, status, created_at desc);

