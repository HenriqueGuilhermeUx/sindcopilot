create or replace function public.reserve_partner_offer(
  p_user_id uuid,
  p_plan_key text
)
returns table (
  referral_id bigint,
  partner_id bigint,
  code_id bigint,
  campaign_key text,
  promo_reserved boolean,
  promo_price_cents integer,
  regular_price_cents integer,
  commission_percent numeric,
  commission_months integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ref public.partner_referrals%rowtype;
  v_partner public.partner_profiles%rowtype;
  v_campaign public.promotion_campaigns%rowtype;
begin
  select * into v_ref
  from public.partner_referrals
  where user_id = p_user_id
  for update;

  if not found then return; end if;

  select * into v_partner
  from public.partner_profiles
  where id = v_ref.partner_id and status = 'active';

  if not found then return; end if;

  if v_ref.campaign_key is not null then
    select * into v_campaign
    from public.promotion_campaigns
    where key = v_ref.campaign_key
    for update;
  end if;

  if v_ref.promo_reserved = false
     and v_campaign.key is not null
     and v_campaign.active = true
     and v_campaign.plan_key = p_plan_key
     and v_campaign.starts_at <= now()
     and (v_campaign.ends_at is null or v_campaign.ends_at > now())
     and v_campaign.reserved_count < v_campaign.max_redemptions then

    update public.promotion_campaigns
    set reserved_count = reserved_count + 1
    where key = v_campaign.key;

    update public.partner_referrals
    set promo_reserved = true,
        promo_price_cents = v_campaign.promo_price_cents,
        regular_price_cents = v_campaign.regular_price_cents,
        reserved_at = now()
    where id = v_ref.id
    returning * into v_ref;
  end if;

  return query
  select
    v_ref.id,
    v_ref.partner_id,
    v_ref.code_id,
    v_ref.campaign_key,
    v_ref.promo_reserved,
    v_ref.promo_price_cents,
    v_ref.regular_price_cents,
    v_partner.commission_percent,
    v_partner.commission_months;
end;
$$;

revoke all on function public.reserve_partner_offer(uuid,text) from public, anon, authenticated;
grant execute on function public.reserve_partner_offer(uuid,text) to service_role;

