alter table public.obligations
  add column if not exists responsible_name text,
  add column if not exists evidence_document_id bigint references public.documents(id) on delete set null,
  add column if not exists started_at timestamptz;

alter table public.financial_transactions
  add column if not exists approval_status text not null default 'not_required'
    check (approval_status in ('not_required','pending','approved','rejected')),
  add column if not exists approval_note text,
  add column if not exists approved_by uuid references public.users(id) on delete set null,
  add column if not exists approved_at timestamptz;

create table if not exists public.supplier_assignments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  supplier_id bigint not null references public.suppliers(id) on delete cascade,
  condominium_id bigint not null references public.condominiums(id) on delete cascade,
  contract_document_id bigint references public.documents(id) on delete set null,
  service_description text,
  start_date date,
  end_date date,
  status text not null default 'active' check (status in ('active','inactive')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, supplier_id, condominium_id)
);

drop trigger if exists supplier_assignments_updated_at on public.supplier_assignments;
create trigger supplier_assignments_updated_at
before update on public.supplier_assignments
for each row execute function public.set_updated_at();

alter table public.supplier_assignments enable row level security;
revoke all on public.supplier_assignments from anon, authenticated;
revoke all on sequence public.supplier_assignments_id_seq from anon, authenticated;
grant all on public.supplier_assignments to service_role;
grant usage, select on sequence public.supplier_assignments_id_seq to service_role;

alter table public.promotion_campaigns
  add column if not exists promo_months integer not null default 12 check (promo_months between 1 and 60);

update public.promotion_campaigns
set promo_price_cents = 4990,
    regular_price_cents = 7990,
    promo_months = 12,
    max_redemptions = 100,
    active = true,
    updated_at = now()
where key = 'FOUNDERS100';

alter table public.users
  add column if not exists woovi_promo_started_at timestamptz,
  add column if not exists woovi_promo_months integer,
  add column if not exists woovi_regular_price_cents integer;

create index if not exists obligations_evidence_document_idx on public.obligations(evidence_document_id);
create index if not exists obligations_condominium_status_due_idx on public.obligations(condominium_id, status, due_date);
create index if not exists financial_transactions_approval_idx on public.financial_transactions(condominium_id, approval_status, posted_at);
create index if not exists financial_transactions_approved_by_idx on public.financial_transactions(approved_by);
create index if not exists supplier_assignments_supplier_idx on public.supplier_assignments(supplier_id, status);
create index if not exists supplier_assignments_condominium_idx on public.supplier_assignments(condominium_id, status);
